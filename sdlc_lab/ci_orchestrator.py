def load_scanner_reports_from_dir(scanners_dir: Path) -> Dict[str, Any]:
    """Ingest scanner JSON files generated by GitHub Actions jobs."""
    reports: Dict[str, Any] = {}
    if not scanners_dir.exists():
        return reports

    gitleaks_file = scanners_dir / "gitleaks-report.json"
    if gitleaks_file.exists():
        try:
            reports["gitleaks"] = json.loads(gitleaks_file.read_text(encoding="utf-8"))
        except Exception:
            reports["gitleaks"] = []

    semgrep_file = scanners_dir / "semgrep-report.json"
    if semgrep_file.exists():
        try:
            reports["semgrep"] = json.loads(semgrep_file.read_text(encoding="utf-8"))
        except Exception:
            reports["semgrep"] = {"results": []}

    osv_file = scanners_dir / "osv-report.json"
    if osv_file.exists():
        try:
            reports["osv"] = json.loads(osv_file.read_text(encoding="utf-8"))
        except Exception:
            reports["osv"] = {"results": []}

    ruff_file = scanners_dir / "ruff-report.json"
    eslint_file = scanners_dir / "eslint-report.json"
    linters_list = []
    if ruff_file.exists():
        try:
            raw_ruff = json.loads(ruff_file.read_text(encoding="utf-8"))
            if isinstance(raw_ruff, list):
                for item in raw_ruff:
                    linters_list.append({
                        "tool": "ruff",
                        "code": item.get("code", "LINT"),
                        "filename": item.get("filename", ""),
                        "line": item.get("location", {}).get("row"),
                        "message": item.get("message", "")
                    })
        except Exception:
            pass
    if eslint_file.exists():
        try:
            raw_eslint = json.loads(eslint_file.read_text(encoding="utf-8"))
            if isinstance(raw_eslint, list):
                for file_entry in raw_eslint:
                    for msg in file_entry.get("messages", []):
                        linters_list.append({
                            "tool": "eslint",
                            "code": msg.get("ruleId", "ESLINT"),
                            "filename": file_entry.get("filePath", ""),
                            "line": msg.get("line"),
                            "message": msg.get("message", "")
                        })
        except Exception:
            pass

    if linters_list:
        reports["linters"] = linters_list

    return reports


