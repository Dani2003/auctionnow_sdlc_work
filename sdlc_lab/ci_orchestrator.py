def evaluate_branch_policy(
    target_branch: str,
    stage1: Dict[str, Any],
    stage2: Dict[str, Any],
    stage3: Dict[str, Any],
    candidate_commit: str,
    automated_tests: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """Enforces AuctionNow branch promotion policies: dev -> stage -> prod via declarative policy engine."""
    return evaluate_branch_compliance(
        target_branch=target_branch,
        stage1=stage1,
        stage2=stage2,
        stage3=stage3,
        candidate_commit=candidate_commit,
        automated_tests=automated_tests
    )


def generate_step_summary_md(
    report: Dict[str, Any],
    stage1: Dict[str, Any],
    stage2: Dict[str, Any],
    stage3: Dict[str, Any],
    stage4: Dict[str, Any],
    target_branch: str
) -> str:
    """Generates a rich GitHub Actions Step Summary markdown document."""
    commit = report["pr"]["commit_sha"]
    status = stage4["status"]
    status_icon = "✅" if status == "PASS" else ("⚠️" if status == "NEEDS_HUMAN_REVIEW" else "🛑")

    md = [
        f"# {status_icon} AuctionNow SDLC Quality & Governance Report",
        f"**Target Branch:** `{target_branch}` | **Commit SHA:** `{commit[:10]}` | **Status:** **`{status}`**\n",
        "---",
        "## 1. Governance Stage Summary",
        "| Stage | Assigned Role | Approver | Artifact Digest | Status |",
        "| :--- | :--- | :--- | :--- | :--- |",
    ]

    role_map = {
        "agent_1_review": ("Tech Lead", "Shahbaz / Saif"),
        "agent_2_test_plan": ("Senior Dev", "Shahzeb / Tooba"),
        "agent_3_qa_plan": ("QA Lead", "Saira / Tabbasum"),
        "agent_4_release_summary": ("Release Manager", "Hassan / Shahbaz"),
    }

    stages_to_render = report.get("stages") or [
        {"stage": "agent_1_review", "artifact": stage1},
        {"stage": "agent_2_test_plan", "artifact": stage2},
        {"stage": "agent_3_qa_plan", "artifact": stage3},
        {"stage": "agent_4_release_summary", "artifact": stage4},
    ]
    approvals_to_check = report.get("approvals") or stage4.get("approvals", [])

    for stage_entry in stages_to_render:
        s_name = stage_entry["stage"]
        role_title, name = role_map.get(s_name, ("Operator", "Reviewer"))
        art = stage_entry["artifact"]
        art_hash = compute_sha256(art)[:12]
        st = "APPROVED" if any(a.get("stage") == s_name and a.get("decision") == "approve" for a in approvals_to_check) else "BLOCKED"
        md.append(f"| `{s_name}` | **{role_title}** | {name} | `{art_hash}...` | **{st}** |")

    md.extend([
        "\n---",
        "## 2. Deterministic Scanners & Quality Findings",
        f"- **Tools Executed:** {', '.join(stage1.get('tools_executed', ['None']))}",
        f"- **Confirmed Scanner Findings:** {stage1.get('confirmed_findings_count', 0)}",
        f"- **Contextual Advisory Findings:** {stage1.get('unconfirmed_findings_count', 0)}",
        f"- **Policy Blocked:** `{'YES' if stage1.get('policy_blocked') else 'NO'}`\n",
        "| Finding ID | Tool | Severity | Category | File:Line | Description |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |",
    ])

    for f in stage1.get("findings", []):
        tool = f.get("source_tool", "unknown")
        fid = f.get("finding_id")
        sev = f.get("severity", "info").upper()
        cat = f.get("category", "")
        loc = f"{f.get('file_path', '')}:{f.get('line_number') or ''}"
        desc = f.get("summary", "")
        md.append(f"| `{fid}` | `{tool}` | **{sev}** | `{cat}` | `{loc}` | {desc} |")

    md.extend([
        "\n---",
        "## 3. SDET Test Proposals & QA Matrix",
        f"- **Test Proposals Generated:** {len(stage2.get('test_cases', []))} test cases across 6 dimensions",
        f"- **Target Surfaces:** Backend API, Database, Mobile React Native (`AcceptQuoteButton.tsx`)",
        f"- **Clarification Requests:** {len(stage2.get('clarification_requests', []))} pending business rule questions",
        f"- **Manual QA Scenarios for Stage APK:** {len(stage3.get('manual_test_matrix', []))} scenarios\n",
        "---",
        "## 4. Mobile Stage APK & QA Handoff Notice",
        "> [!IMPORTANT]",
        f"> **AuctionNow Release Flow:** Code merged into `stage` triggers the internal Stage APK build. The QA team executes the manual test matrix on the real Stage APK build before promoting from `stage` to `prod`.",
        "\n---",
        f"**Machine-readable audit trail written to:** `artifacts/latest_run.json`"
    ])

    return "\n".join(md)


def run_ci(
    target_branch: str,
    commit_sha: str,
    pr_id: str,
    scanners_dir: Path,
    tests_file: Optional[Path] = None,
    output_file: Optional[Path] = None,
    output_path: Optional[Path] = None,
    summary_path: Optional[Path] = None
) -> Dict[str, Any]:
    """Main execution function for CI runner. Returns full audit report dictionary."""
    print("=================================================================")
    print(" AuctionNow SDLC CI/CD Governance Runner")
    print(f" Target Branch: {target_branch} | Commit: {commit_sha[:10]} | PR: {pr_id}")
    print("=================================================================")

    # 1. Load PR & Requirements Fixtures / Context
    pr_path = ROOT / "fixtures/sample_pr.json"
    reqs_path = ROOT / "fixtures/sample_requirements.json"
    pr = json.loads(pr_path.read_text(encoding="utf-8")) if pr_path.exists() else {"pr_id": pr_id, "commit_sha": commit_sha}
    pr["commit_sha"] = commit_sha
    pr["pr_id"] = pr_id
    reqs = json.loads(reqs_path.read_text(encoding="utf-8")) if reqs_path.exists() else {"acceptance_criteria": []}

    # 2. Ingest Scanner Reports
    scanner_reports = load_scanner_reports_from_dir(scanners_dir)
    print(f"Loaded scanner reports: {list(scanner_reports.keys())}")

    # 3. Ingest Automated Tests Evidence
    # sample_ci_evidence.json wraps test results under "automated_test_results";
    # real CI artifact directly is that dict.
    automated_tests = None
    if tests_file and tests_file.exists():
        try:
            raw = json.loads(tests_file.read_text(encoding="utf-8"))
            # Unwrap if nested (fixture format)
            automated_tests = raw.get("automated_test_results", raw)
        except Exception:
            pass

    # 3b. If no scanners loaded from CI dir, fall back to fixture for local dev/demo runs
    if not scanner_reports:
        fallback = ROOT / "fixtures/sample_scanner_reports.json"
        if fallback.exists():
            try:
                scanner_reports = json.loads(fallback.read_text(encoding="utf-8"))
                print(f"No CI scanner dir found; loaded fixture scanners: {list(scanner_reports.keys())}")
            except Exception:
                pass

    # 4. Run Stage 1 (Quality & Security Review)
    stage1 = code_quality_security_review(pr, scanner_reports=scanner_reports, candidate_commit=commit_sha)
    validate_stage_artifact("agent_1_review", stage1)

    # 5. Run Stage 2 (SDET Test Planner)
    stage2 = sdet_test_plan(pr, reqs, review=stage1, candidate_commit=commit_sha)
    validate_stage_artifact("agent_2_test_plan", stage2)

    # 6. Run Stage 3 (QA Director Matrix)
    stage3 = qa_directives(pr, stage2, stage1, automated_test_results=automated_tests, candidate_commit=commit_sha)
    validate_stage_artifact("agent_3_qa_plan", stage3)

    # 7. Evaluate Branch Promotion Policy
    policy = evaluate_branch_policy(target_branch, stage1, stage2, stage3, commit_sha, automated_tests)

    # 8. Run Stage 4 (Release & CI Evidence Gate)
    evidence_payload = {
        "pr_id": pr_id,
        "commit_sha": commit_sha,
        "evidence_commit_sha": commit_sha,
        "ci_passed": policy["ci_passed"],
        "qa_signed_off": policy["qa_signed_off"],
        "unresolved_high_findings": policy["unresolved_high_findings"],
        "advisory_warnings_count": stage1.get("unconfirmed_findings_count", 0)
    }

    stage4 = release_evidence_summary(
        evidence=evidence_payload,
        candidate_commit=commit_sha,
        pr_id=pr_id,
        approvals=policy["approvals"]
    )
    validate_stage_artifact("agent_4_release_summary", stage4)

    # 9. Build Comprehensive Report
    report: Dict[str, Any] = {
        "workflow_version": "1.0.0",
        "run_mode": "AUCTIONNOW_CI_PIPELINE",
        "target_branch": target_branch,
        "started_at_utc": datetime.now(timezone.utc).isoformat(),
        "pr": {
            "pr_id": pr_id,
            "commit_sha": commit_sha,
            "title": pr.get("title", "Pull Request"),
            "changed_files": pr.get("changed_files", []),
        },
        "stages": [
            {"stage": "agent_1_review", "artifact": stage1},
            {"stage": "agent_2_test_plan", "artifact": stage2},
            {"stage": "agent_3_qa_plan", "artifact": stage3},
            {"stage": "agent_4_release_summary", "artifact": stage4},
        ],
        "approvals": policy["approvals"],
        "final_decision": stage4["status"],
        "final_status": stage4["status"],
        "policy_blockers": policy["policy_blockers"],
        "policy_warnings": policy["policy_warnings"],
        "finished_at_utc": datetime.now(timezone.utc).isoformat()
    }

    # Write output artifact
    out = output_path or output_file or (ROOT / "artifacts/latest_run.json")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(f"Report written to: {out}")

    # Write GitHub Step Summary
    summary_md = generate_step_summary_md(report, stage1, stage2, stage3, stage4, target_branch)
    step_summary_file = summary_path or (out.parent / "step_summary.md")
    step_summary_file.parent.mkdir(parents=True, exist_ok=True)
    step_summary_file.write_text(summary_md, encoding="utf-8")
    print(f"Step summary written to: {step_summary_file}")
    print(f"Final Decision: {stage4['status']}")

    return report


def main():
    parser = argparse.ArgumentParser(description="AuctionNow CI SDLC Orchestrator")
    parser.add_argument("--target-branch", default="dev", help="Target branch for PR/push (dev, stage, prod)")
    parser.add_argument("--commit-sha", default="test-sha-123456", help="Git commit SHA")
    parser.add_argument("--pr-id", default="PR-104", help="Pull request ID")
    parser.add_argument("--scanners-dir", default="artifacts/scanners", help="Directory containing scanner JSON reports")
    parser.add_argument("--tests-file", default="artifacts/tests/automated-tests.json", help="Automated test report JSON")
    parser.add_argument("--output", default="artifacts/latest_run.json", help="Output audit JSON file path")
    args = parser.parse_args()

    report = run_ci(
        target_branch=args.target_branch,
        commit_sha=args.commit_sha,
        pr_id=args.pr_id,
        scanners_dir=Path(args.scanners_dir),
        tests_file=Path(args.tests_file) if args.tests_file else None,
        output_file=Path(args.output) if args.output else None
    )
    exit_code = 0 if report.get("final_status") in ("PASS", "NEEDS_HUMAN_REVIEW") else 1
    sys.exit(exit_code)


if __name__ == "__main__":
    main()
